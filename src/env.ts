// Bindings available to the Worker. Runtime types come from `bun run cf-typegen`
// (worker-configuration.d.ts); this interface is the single source of truth for vars and secrets.
// Secrets are optional because the Worker is deployed before every key exists: check before use.
export interface Env {
  // vars (wrangler.jsonc)
  PUBLIC_URL: string;

  // secrets: needed now
  DATABASE_URL?: string;
  NAIVE_API_KEY?: string;
  AGENTMAIL_API_KEY?: string;
  MONID_API_KEY?: string;
  HUBSPOT_ACCESS_TOKEN?: string;
  NOTION_API_TOKEN?: string;
  CLERK_SECRET_KEY?: string;
  CLERK_PUBLISHABLE_KEY?: string;

  // secrets: generated by us
  MCP_TOKEN?: string;

  // secrets: written by scripts/setup.ts
  NAIVE_WEBHOOK_SECRET?: string;
  NAIVE_VAULT_ID?: string;
  AGENTMAIL_INBOX_ID?: string;
  AGENTMAIL_WEBHOOK_SECRET?: string;

  // secrets: later (Photon / iMessage)
  SPECTRUM_PROJECT_ID?: string;
  SPECTRUM_PROJECT_SECRET?: string;
  OWNER_PHONE?: string;
}

type SecretKey = { [K in keyof Env]-?: undefined extends Env[K] ? K : never }[keyof Env];

/** Returns a secret or throws a clear error naming the missing key. */
export function requireEnv(env: Env, key: SecretKey): string {
  const value = env[key];
  if (!value) throw new Error(`Missing secret ${key}. Add it to .dev.vars and run \`wrangler secret bulk .dev.vars\`.`);
  return value;
}
