// Bindings available to the Worker. Runtime types come from `bun run cf-typegen`
// (worker-configuration.d.ts); this interface is the single source of truth for vars and secrets.
// Secrets are optional because the Worker is deployed before every key exists: check before use.
export interface Env {
  // vars (wrangler.jsonc)
  PUBLIC_URL: string;

  // Static-assets binding for the web app (wrangler.jsonc `assets.binding`). Optional: absent until the SPA ships.
  ASSETS?: Fetcher;

  // secrets: needed now
  DATABASE_URL?: string;
  NAIVE_API_KEY?: string;
  AGENTMAIL_API_KEY?: string;
  APIFY_TOKEN?: string;
  HUBSPOT_ACCESS_TOKEN?: string;
  NOTION_API_TOKEN?: string;
  CLERK_SECRET_KEY?: string;
  CLERK_PUBLISHABLE_KEY?: string;
  // Clerk session verification for /api/* (see src/api/auth.ts). CLERK_JWT_KEY (PEM public key) makes it
  // networkless; without it the JWKS is fetched with CLERK_SECRET_KEY. Comma-separated lists.
  CLERK_JWT_KEY?: string;
  CLERK_AUTHORIZED_PARTIES?: string;
  CLERK_ALLOWED_USER_IDS?: string;

  // secrets: generated by us
  MCP_TOKEN?: string;

  // Billing (src/billing/*). Crusonia's own Stripe account: a test key first, a live restricted key to go live.
  STRIPE_SECRET_KEY?: string;
  // Verifies POST /webhooks/stripe; written by `bun run setup --stripe` to a private file (never printed).
  STRIPE_WEBHOOK_SECRET?: string;
  // "true" blocks paid work (onboarding propose, leads/find, research) with 402 insufficient_credits when the
  // caller's balance is <= 0. Default off, so the owner's dogfooding never blocks. MCP_TOKEN always bypasses it.
  BILLING_ENFORCED?: string;
  // Free-sample credits granted once per new billing account (default in src/billing/plans.ts; "0" turns it off).
  BILLING_FREE_CREDITS?: string;

  // secrets: written by scripts/setup.ts
  NAIVE_WEBHOOK_SECRET?: string;
  NAIVE_VAULT_ID?: string;
  NAIVE_AGENT_ID?: string;
  AGENTMAIL_INBOX_ID?: string;
  AGENTMAIL_WEBHOOK_SECRET?: string;

  // config (optional; defaults in code)
  // Tools the Naive agent may run without asking the owner: comma list, `*` suffix wildcards.
  AUTO_CONFIRM_TOOLS?: string;
  // Hard cap in USD on every Apify Actor run Crusonia starts (maxTotalChargeUsd), default 0.25 (src/services/apify.ts).
  APIFY_MAX_CHARGE_USD?: string;
  // Days to keep each agent session's full event trace (src/services/traces.ts), default 180.
  TRACE_RETENTION_DAYS?: string;
  // Approval lifetimes (src/services/approval-ttl.ts). Hours before a send approval (email draft) expires,
  // default 168 (7 days); minutes before an agent tool or question approval expires, default 60.
  SEND_APPROVAL_TTL_HOURS?: string;
  TOOL_APPROVAL_TTL_MINUTES?: string;
  // Weekly Naive spend budget in USD, shown next to the week's spend on the dashboard (display only).
  WEEKLY_BUDGET_USD?: string;

  // CRM sync (src/services/crm-sync.ts). Both switches default to off: nothing is written to HubSpot or Notion
  // until one is "true". The HubSpot import only reads from HubSpot and works with just the token.
  HUBSPOT_SYNC_ENABLED?: string;
  NOTION_SYNC_ENABLED?: string;
  // Which leads are pushed: "qualified" (default: opted in, qualified, in the send flow, or already in HubSpot
  // and scored) or "all".
  HUBSPOT_SYNC_SCOPE?: string;
  NOTION_SYNC_SCOPE?: string;
  // HubSpot import: the contact property that records an email opt-in, and the values that count as yes
  // (comma list, case-insensitive; default yes/true/1/...). Unset = imported contacts never get consent.
  HUBSPOT_CONSENT_PROPERTY?: string;
  HUBSPOT_CONSENT_VALUES?: string;
  // The "Crusonia leads" database (written by `bun run setup --crm --write`).
  NOTION_LEADS_DATABASE_ID?: string;
  // Leads synced per target per cron run (default 5). Keep it small on the Workers Free plan (50 subrequests).
  CRM_SYNC_BATCH_SIZE?: string;

  // iMessage approvals through Photon (src/services/imessage.ts, bridge/). The Photon credentials
  // (SPECTRUM_PROJECT_ID / SPECTRUM_PROJECT_SECRET) live only on the bridge, never on the Worker.
  // The bridge only calls the Worker (it accepts no inbound traffic), so the Worker needs no bridge URL.
  // "true" turns it on (default off): new approvals and expiry reminders are texted, owner replies are applied.
  IMESSAGE_ENABLED?: string;
  // Shared HMAC secret signing the bridge's calls to /webhooks/photon and /webhooks/photon/poll. `openssl rand -hex 32`.
  BRIDGE_SECRET?: string;
  // "true" also texts approvals that belong to integration-test fixtures (leads with an it_* source, reserved example
  // domains, ses_it_* sessions). Off by default so test suites on a shared database never text the owner.
  IMESSAGE_INCLUDE_TEST_DATA?: string;
  // Send cap: notices texted per 10 minutes before the rest collapse into one "+N more" text (default 6).
  IMESSAGE_NOTICE_CAP?: string;
  // Owner's phone in E.164. Optional on the Worker: when set, /webhooks/photon also refuses any other sender
  // (the bridge already filters; this is defense in depth).
  OWNER_PHONE?: string;
}

type SecretKey = { [K in keyof Env]-?: undefined extends Env[K] ? (Env[K] extends string | undefined ? K : never) : never }[keyof Env];

/** Returns a secret or throws a clear error naming the missing key. */
export function requireEnv(env: Env, key: SecretKey): string {
  const value = env[key];
  if (!value) throw new Error(`Missing secret ${key}. Add it to .dev.vars and run \`wrangler secret bulk .dev.vars\`.`);
  return value;
}
